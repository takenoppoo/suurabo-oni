# ===== 例題3 払えない最大金額 =====
def unpay(a,b): 
    ok=set(); N=a*b+5
    for x in range(N):
        for y in range(N):
            if a*x+b*y<=N: ok.add(a*x+b*y)
    return max(n for n in range(N) if n not in ok)
