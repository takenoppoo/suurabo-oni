def paths(W,H,avoid=None):
    dp={(0,0):1}
    for x in range(W+1):
        for y in range(H+1):
            if (x,y)==(0,0): continue
            if avoid==(x,y): dp[(x,y)]=0; continue
            dp[(x,y)]=dp.get((x-1,y),0)+dp.get((x,y-1),0)
    return dp[(W,H)]
