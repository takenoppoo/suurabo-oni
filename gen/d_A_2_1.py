    for p in itertools.permutations(people):
        k=min(p[i:]+p[:i] for i in range(n)) if False else None
        if p[0]!=0: continue   # 人0を固定すれば回転の重複なし
        allc+=1
        sex=[1 if x<nm else 0 for x in p]
        if all(sex[i]!=sex[(i+1)%n] for i in range(n)): alt+=1
    return allc,alt
