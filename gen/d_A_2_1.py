# ===== 例題3 組分け =====
def parts(n,sizes):   # 区別なしの組分け数 / 区別ありの部屋数
    people=range(n)
    def rec(rem,sz):
        if not sz: return [[]]
        out=[]
        for c in itertools.combinations(rem,sz[0]):
            rest=[x for x in rem if x not in c]
            for r in rec(rest,sz[1:]): out.append([frozenset(c)]+r)
        return out
    allp=rec(list(people),list(sizes))
    return len(allp),len({frozenset(p) for p in allp})
