def ballp(R,W,B,n,pred):
    balls=['R']*R+['W']*W+['B']*B; c=t=0
    for idx in itertools.combinations(range(len(balls)),n):
        t+=1; s=[balls[i] for i in idx]
        if pred(s): c+=1
    return Fr(c,t)
