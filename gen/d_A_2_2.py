def first_to(a_need,b_need,p):   # A があと a_need 勝、B があと b_need 勝で優勝
    from functools import lru_cache
    @lru_cache(None)
    def f(a,b):
        if a==0: return Fr(1)
        if b==0: return Fr(0)
        return p*f(a-1,b)+(1-p)*f(a,b-1)
    return f(a_need,b_need)
