def janken(n):
    res={}
    for hands in itertools.product(range(3),repeat=n):
        s=set(hands)
        if len(s)!=2: w=0   # あいこ
        else:
            a,b=sorted(s); win=a if (b-a)==2 else b if False else None
            # 0=グー 1=チョキ 2=パー: 勝ち 0>1,1>2,2>0
            beats={0:1,1:2,2:0}
            x,y=tuple(s); win=x if beats[x]==y else y
            w=sum(1 for h in hands if h==win)
        res[w]=res.get(w,0)+1
    return res
