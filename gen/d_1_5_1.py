def med(v):
    s=sorted(v); n=len(s); return Fr(s[n//2]) if n%2 else (Fr(s[n//2-1])+Fr(s[n//2]))/2
def quart(v):
    s=sorted(v); n=len(s); lo=s[:n//2]; hi=s[(n+1)//2:]; return med(lo),med(s),med(hi)
