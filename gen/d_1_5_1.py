def grp(vals,freq):
    n=sum(freq); mean=Fr(sum(Fr(v)*f for v,f in zip(vals,freq)),n)
    ex_=[v for v,f in zip(vals,freq) for _ in range(f)]; return mean,med(ex_),vals[freq.index(max(freq))]
assert grp([5,15,25,35],[4,6,8,2])==(19,20,25)
assert grp([10,30,50,70],[3,7,6,4])==(41,40,30)
assert grp([Fr(5,2),Fr(15,2),Fr(25,2),Fr(35,2)],[2,5,9,4])==(Fr(45,4),Fr(25,2),Fr(25,2))
assert grp([55,65,75,85,95],[1,4,10,3,2])==(Fr(151,2),75,75)

