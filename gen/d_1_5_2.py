# 実データでも確認
import random
random.seed(1)
def mk(n,m,v):  # 平均m分散vの整数データを作る(n偶数,±d)
    d=int(math.isqrt(v)); assert d*d==v
    return [m+d]*(n//2)+[m-d]*(n//2)
