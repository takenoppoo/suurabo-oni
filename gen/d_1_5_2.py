from fractions import Fraction as Fr
EXS=[]
def ex(**k): EXS.append(k)
def mean(v): return Fr(sum(v),len(v))
def var(v): m=mean(v); return sum((Fr(a)-m)**2 for a in v)/len(v)
def cov(x,y): mx,my=mean(x),mean(y); return sum((Fr(a)-mx)*(Fr(b)-my) for a,b in zip(x,y))/len(x)

