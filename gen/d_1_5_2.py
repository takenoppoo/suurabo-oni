# ===== 例題4 2グループを合わせた分散 =====
nA,mA,vA,nB,mB,vB=10,60,20,30,80,40
def comb(nA,mA,vA,nB,mB,vB):
    n=nA+nB; m=Fr(nA*mA+nB*mB,n); v=(nA*(vA+mA**2)+nB*(vB+mB**2))/Fr(n)-m**2; return m,v
m4,v4=comb(nA,mA,vA,nB,mB,vB)
