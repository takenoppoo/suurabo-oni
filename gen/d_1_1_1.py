def combos(n,k):
    out=[]
    for a2 in range(n+1):
        b1=k-2*a2
        if b1<0: continue
        c0=n-a2-b1
        if c0<0: continue
        out.append((a2,b1,c0,F(n)//(F(a2)*F(b1)*F(c0))))
    return out
def p2_steps(n,k):
    cs=combos(n,k); rows=""
    for a2,b1,c0,v in cs:
        rows+=f'<tr><td>{a2}</td><td>{b1}</td><td>{c0}</td><td>{I(f"\\dfrac{{{n}!}}{{{a2}!\\,{b1}!\\,{c0}!}}={v}")}</td></tr>'
    tot=sum(v for *_,v in cs)
    return (f'<p>{I("x^2")} を a 個、{I("x")} を b 個、{I("1")} を c 個選ぶとして {I(f"a+b+c={n},\\ 2a+b={k}")}。</p>'
      f'<table class="tbl"><tr><th>a</th><th>b</th><th>c</th><th>選び方</th></tr>{rows}</table>'
      f'<p>合計 {I("+".join(str(v) for *_,v in cs)+"="+str(tot))}</p>'), tot

