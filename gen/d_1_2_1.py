from fractions import Fraction as Fr
def sub(Aok,Bok,rng):
    return [a for a in (Fr(k,4) for k in rng) if all(Aok(t) for t in (Fr(j,8) for j in range(-160,160)) if Bok(t,a))]
g=sub(lambda t:-2<=t<3,lambda t,a:a-1<=t<=a+2,range(-40,40)); assert min(g)==-1 and max(g)==Fr(3,4)
g=sub(lambda t:-3<t<=4,lambda t,a:a<=t<=a+3,range(-40,40)); assert min(g)==Fr(-11,4) and max(g)==1
g=sub(lambda t:1<=t<=6,lambda t,a:a-2<t<a+1,range(-40,60)); assert min(g)==3 and max(g)==5
